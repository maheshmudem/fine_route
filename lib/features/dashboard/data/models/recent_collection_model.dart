import '../../domain/entities/recent_collection.dart';

class RecentCollectionModel extends RecentCollection {
  const RecentCollectionModel({
    required super.publicId,
    required super.receiptNumber,
    required super.customerCode,
    required super.customerName,
    required super.customerPublicId,
    required super.linePublicId,
    required super.lineName,
    required super.portion,
    required super.disbursedDate,
    required super.customerStartDate,
    required super.totalInstallments,
    required super.installmentsPaidCount,
    required super.remainingInstallmentsCount,
    required super.outstandingBalance,
    required super.skippedInstallmentsCount,
    required super.collectionDate,
    required super.expectedAmount,
    required super.collectedAmount,
    required super.status,
    required super.statusCode,
    required super.statusName,
    required super.paymentMode,
    required super.paymentModeName,
    required super.remarks,
    required super.isCollectedToday,
    required super.isEdited,
    required super.editCount,
    required super.createdAt,
  });

  factory RecentCollectionModel.fromJson(Map<String, dynamic> json) {
    return RecentCollectionModel(
      publicId: json['public_id'] as String? ?? '',
      receiptNumber: json['receipt_number'] as String? ?? '',
      customerCode: json['customer_code'] as String? ?? '',
      customerName: json['customer_name'] as String? ?? '',
      customerPublicId: json['customer_public_id'] as String? ?? '',
      linePublicId: json['line_public_id'] as String? ?? '',
      lineName: json['line_name'] as String? ?? '',
      portion: json['portion'] as String? ?? '',
      disbursedDate: json['disbursed_date'] as String? ?? '',
      customerStartDate: json['customer_start_date'] as String? ?? '',
      totalInstallments: json['total_installments'] as int? ?? 0,
      installmentsPaidCount: json['installments_paid_count'] as int? ?? 0,
      remainingInstallmentsCount: json['remaining_installments_count'] as int? ?? 0,
      outstandingBalance: double.tryParse(json['outstanding_balance']?.toString() ?? '0') ?? 0.0,
      skippedInstallmentsCount: json['skipped_installments_count'] as int? ?? 0,
      collectionDate: json['collection_date'] as String? ?? '',
      expectedAmount: double.tryParse(json['expected_amount']?.toString() ?? '0') ?? 0.0,
      collectedAmount: double.tryParse(json['collected_amount']?.toString() ?? '0') ?? 0.0,
      status: json['status'] as int? ?? 0,
      statusCode: json['status_code'] as String? ?? '',
      statusName: json['status_name'] as String? ?? '',
      paymentMode: json['payment_mode'] as int? ?? 0,
      paymentModeName: json['payment_mode_name'] as String? ?? '',
      remarks: json['remarks'] as String? ?? '',
      isCollectedToday: json['is_collected_today'] as bool? ?? false,
      isEdited: json['is_edited'] as bool? ?? false,
      editCount: json['edit_count'] as int? ?? 0,
      createdAt: json['created_at'] != null ? DateTime.parse(json['created_at']) : DateTime.now(),
    );
  }
}
